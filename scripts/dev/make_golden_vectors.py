#!/usr/bin/env python3
"""Generates proto/testdata/golden_vectors.json.
Bytes are produced by a tiny hand-written wire encoder AND by the official python protobuf runtime
(descriptors built programmatically from the same field numbers); the script fails if they differ.
It does not parse chat.proto, so keep the tables below in sync with it."""
import json, sys, pathlib
from google.protobuf import descriptor_pb2, descriptor_pool, message_factory
F = descriptor_pb2.FieldDescriptorProto

def varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F; n >>= 7
        if n: out.append(b | 0x80)
        else: out.append(b); return bytes(out)
def tag(num, wt): return varint((num << 3) | wt)
def s(num, v): b = v.encode(); return tag(num, 2) + varint(len(b)) + b
def i(num, v): return tag(num, 0) + varint(v) if v else b""
def m(num, payload): return tag(num, 2) + varint(len(payload)) + payload

vectors = {
 "client_hello": ("ClientEnvelope", s(1,"r1") + m(9, i(1,1) + s(2,"typing") + s(3,"tok"))),
 "client_send_message": ("ClientEnvelope", s(1,"r2") + m(10, s(1,"c1") + s(2,"m1") + s(3,"hi"))),
 "server_accepted": ("ServerEnvelope", s(1,"r2") + m(10, s(1,"x") + s(2,"m1") + i(3,5) + i(4,1700000000000) + s(6,"c1"))),
 "server_error": ("ServerEnvelope", s(1,"r3") + m(12, i(1,3) + s(2,"bad"))),
 "server_new_message": ("ServerEnvelope", m(11, s(1,"x") + s(2,"c1") + s(3,"u1") + s(4,"m1") + s(5,"h\u00e9llo") + i(6,1700000000000) + i(7,6))),
}

# cross-check with official runtime
fd = descriptor_pb2.FileDescriptorProto(name="t.proto", package="chat.v1", syntax="proto3")
def msg(name, fields, oneof=None):
    d = fd.message_type.add(name=name)
    if oneof: d.oneof_decl.add(name=oneof)
    for (fname, num, typ, tname, rep, inone) in fields:
        f = d.field.add(name=fname, number=num, type=typ, label=F.LABEL_REPEATED if rep else F.LABEL_OPTIONAL)
        if tname: f.type_name = tname
        if inone: f.oneof_index = 0
S, I64, U32, MSG, EN = F.TYPE_STRING, F.TYPE_INT64, F.TYPE_UINT32, F.TYPE_MESSAGE, F.TYPE_ENUM
e = fd.enum_type.add(name="ErrorCode")
for n, v in [("ERROR_CODE_UNSPECIFIED",0),("ERROR_CODE_UNSUPPORTED_VERSION",1),("ERROR_CODE_UNAUTHENTICATED",2),("ERROR_CODE_INVALID_ARGUMENT",3)]: e.value.add(name=n, number=v)
msg("Hello", [("protocol_version",1,U32,None,0,0),("capabilities",2,S,None,1,0),("access_token",3,S,None,0,0)])
msg("SendMessage", [("conversation_id",1,S,None,0,0),("client_message_id",2,S,None,0,0),("text",3,S,None,0,0)])
msg("ClientEnvelope", [("request_id",1,S,None,0,0),("hello",9,MSG,".chat.v1.Hello",0,1),("send_message",10,MSG,".chat.v1.SendMessage",0,1)], "body")
msg("MessageAccepted", [("message_id",1,S,None,0,0),("client_message_id",2,S,None,0,0),("seq",3,I64,None,0,0),("created_at_unix_ms",4,I64,None,0,0),("duplicate",5,F.TYPE_BOOL,None,0,0),("conversation_id",6,S,None,0,0)])
msg("ChatMessage", [("message_id",1,S,None,0,0),("conversation_id",2,S,None,0,0),("sender_id",3,S,None,0,0),("client_message_id",4,S,None,0,0),("text",5,S,None,0,0),("created_at_unix_ms",6,I64,None,0,0),("seq",7,I64,None,0,0)])
msg("ProtocolError", [("code",1,EN,".chat.v1.ErrorCode",0,0),("message",2,S,None,0,0)])
msg("ServerEnvelope", [("request_id",1,S,None,0,0),("accepted",10,MSG,".chat.v1.MessageAccepted",0,1),("new_message",11,MSG,".chat.v1.ChatMessage",0,1),("error",12,MSG,".chat.v1.ProtocolError",0,1)], "body")
pool = descriptor_pool.DescriptorPool(); pool.Add(fd)
def cls(n): return message_factory.GetMessageClass(pool.FindMessageTypeByName("chat.v1."+n))
C, Sv = cls("ClientEnvelope"), cls("ServerEnvelope")
official = {}
x = C(request_id="r1"); x.hello.protocol_version=1; x.hello.capabilities.append("typing"); x.hello.access_token="tok"; official["client_hello"]=x
x = C(request_id="r2"); x.send_message.conversation_id="c1"; x.send_message.client_message_id="m1"; x.send_message.text="hi"; official["client_send_message"]=x
x = Sv(request_id="r2"); a=x.accepted; a.message_id="x"; a.client_message_id="m1"; a.seq=5; a.created_at_unix_ms=1700000000000; a.conversation_id="c1"; official["server_accepted"]=x
x = Sv(request_id="r3"); x.error.code=3; x.error.message="bad"; official["server_error"]=x
x = Sv(); n=x.new_message; n.message_id="x"; n.conversation_id="c1"; n.sender_id="u1"; n.client_message_id="m1"; n.text="h\u00e9llo"; n.created_at_unix_ms=1700000000000; n.seq=6; official["server_new_message"]=x
ok = True
for name, (typ, raw) in vectors.items():
    off = official[name].SerializeToString(deterministic=True)
    if off != raw: ok = False; print("MISMATCH", name, off.hex(), raw.hex())
if not ok: sys.exit(1)
out = {"note": "Golden protobuf vectors; generated by scripts/dev/make_golden_vectors.py and cross-checked with the python protobuf runtime.",
       "vectors": [{"name": n, "type": t, "hex": b.hex()} for n, (t, b) in vectors.items()]}
pathlib.Path(__file__).resolve().parents[2].joinpath("proto/testdata/golden_vectors.json").write_text(json.dumps(out, indent=2) + "\n")
print("OK: wrote", len(vectors), "vectors; hand encoder == official runtime")
